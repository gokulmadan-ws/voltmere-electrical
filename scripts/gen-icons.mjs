// scripts/gen-icons.mjs: one-off generator that writes js/ui/icons.js from lucide-static.
// Owner: WP2
//
// Usage (the repo has no node_modules, so install lucide-static into a throwaway folder first):
//   npm i --prefix /tmp/some-folder lucide-static@1.61.0
//   LUCIDE_DIR=/tmp/some-folder node electrician/scripts/gen-icons.mjs
// Reads <LUCIDE_DIR>/node_modules/lucide-static/icons/<name>.svg and writes ../js/ui/icons.js.
// Only the six element types the chosen icons use are handled (path, rect, circle, line, polyline, polygon).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

// The exact list from contract section 4.9. Do not add names here without the contract.
const NAMES = `zap phone message-circle calendar calendar-days calendar-check calendar-x clock
shield-check badge-check file-check file-text clipboard-check star map-pin house building-2
plug plug-zap lightbulb wrench toggle-right siren triangle-alert bell bell-ring
check check-check circle-check circle-x circle-alert info
chevron-left chevron-right chevron-down chevron-up arrow-left arrow-right x plus search ellipsis
settings user users inbox receipt pound-sterling navigation truck ban rotate-ccw undo-2
download external-link copy send share-2 smartphone moon sun sun-moon history list-checks lock refresh-cw gauge`
  .split(/\s+/).filter(Boolean);

const TAGS = new Set(['path', 'rect', 'circle', 'line', 'polyline', 'polygon']);

const lucideDir = process.env.LUCIDE_DIR;
if (!lucideDir) {
  console.error('Set LUCIDE_DIR to the folder you ran "npm i --prefix <folder> lucide-static" in.');
  process.exit(1);
}
const pkgDir = join(lucideDir, 'node_modules', 'lucide-static');
const version = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8')).version;

/** Parse the child elements of a lucide svg file into [tag, attrs] pairs. */
function parseSvg(name) {
  const svg = readFileSync(join(pkgDir, 'icons', name + '.svg'), 'utf8');
  const inner = svg.replace(/<!--[\s\S]*?-->/g, '').replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  const out = [];
  const elRe = /<([a-z]+)\s([^>]*?)\/>/g;
  let m;
  while ((m = elRe.exec(inner))) {
    const tag = m[1];
    if (!TAGS.has(tag)) throw new Error(`Icon ${name}: unsupported element <${tag}>`);
    const attrs = {};
    const attrRe = /([a-zA-Z][a-zA-Z0-9-]*)="([^"]*)"/g; // digits matter: x1, y2
    let a;
    while ((a = attrRe.exec(m[2]))) attrs[a[1]] = a[2];
    if (!Object.keys(attrs).length) throw new Error(`Icon ${name}: <${tag}> has no attributes`);
    out.push([tag, attrs]);
  }
  if (!out.length) throw new Error(`Icon ${name}: no elements found`);
  return out;
}

const q = (s) => "'" + String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
const lines = NAMES.map((name) => {
  const els = parseSvg(name).map(([tag, attrs]) =>
    `[${q(tag)}, { ${Object.entries(attrs).map(([k, v]) => `${/^[a-zA-Z_$][\w$]*$/.test(k) ? k : q(k)}: ${q(v)}`).join(', ')} }]`);
  return `  ${q(name)}: [${els.join(', ')}]`;
});

const out = `// js/ui/icons.js: icon path data as element arrays (rendered through h(), never as strings).
// Owner: WP2
//
// GENERATED by scripts/gen-icons.mjs from lucide-static ${version}. Do not edit by hand.
// Icons: Lucide (lucide.dev), ISC licence. Copyright (c) for Lucide contributors; portions
// derived from Feather, Copyright (c) 2013-2023 Cole Bemis, MIT licence. Permission to use, copy,
// modify and distribute this data for any purpose with or without fee is granted, provided the
// above notice appears in all copies. The data is provided "as is" without warranty of any kind.
// Stroke 1.75 at 24px, round caps and joins, currentColor (set by Icon in display.js).

export const ICONS = {
${lines.join(',\n')}
};

export const ICON_NAMES = Object.keys(ICONS);
`;

const target = join(dirname(fileURLToPath(import.meta.url)), '..', 'js', 'ui', 'icons.js');
writeFileSync(target, out);
console.log(`Wrote ${NAMES.length} icons (lucide-static ${version}) to ${target}`);
